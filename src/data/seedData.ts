// Helper to construct realistic demo appointments
function createDemoAppointment(
  id: string,
  invoiceNum: string,
  fullName: string,
  email: string,
  phone: string,
  state: string,
  service: ServiceOption,
  provider: Provider,
  date: string,
  timeSlot: string,
  endTimeSlot: string,
  status: 'upcoming' | 'completed' | 'cancelled',
  paymentStatus: 'paid' | 'pending' | 'refunded',
  paymentMethod: 'upi' | 'card' | 'netbanking' | 'venue',
  notes: string,
  discount = 0,
  couponCode?: string,
  customResponses?: Record<string, any>
): Appointment {
  const isInterState = state.toLowerCase() !== 'tamil nadu';
  const pricing = calculateGSTBreakdown({
    basePrice: service.basePrice,
    discountAmount: discount,
    gstRate: service.gstRate,
    state,
    couponCode,
    sacCode: service.sacCode,
  });

  return {
    id,
    invoiceNumber: invoiceNum,
    fullName,
    email,
    phone,
    state,
    isInterState,
    serviceId: service.id,
    serviceName: service.name,
    serviceCategory: service.category,
    serviceMode: service.serviceMode || 'in_person',
    providerId: provider.id,
    providerName: provider.name,
    date,
    timeSlot,
    endTimeSlot,
    isoDateTime: createISTIsoString(date, timeSlot),
    duration: service.duration,
    status,
    paymentStatus,
    paymentMethod,
    pricing,
    notes,
    customFieldResponses: customResponses,
    createdAt: createISTIsoString('2026-10-05', '09:00 AM'),
  };
}

