export interface CustomFieldDefinition {
  id: string;
  label: string;
  type: 'text' | 'select' | 'textarea' | 'checkbox';
  placeholder?: string;
  options?: string[];
  required?: boolean;
  serviceIds?: string[]; // if empty/undefined, applies to all services
  helpText?: string;
  isActive?: boolean;
}

export interface CategoryOption {
  id: string;
  name: string;
  icon?: string;
  description?: string;
  isActive?: boolean;
}

export interface BusinessProfile {
  businessName: string;
  tagline: string;
  legalName: string;
  gstin: string;
  homeState: string;
  homeStateCode: string;
  registeredAddress: string;
  phone: string;
  email: string;
  website: string;
}

